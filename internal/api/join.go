package api

import (
	"crypto/subtle"
	"net"
	"net/http"
	"strings"
	"time"

	"github.com/prezmc/tainerhub/internal/gateway"
	"github.com/prezmc/tainerhub/internal/wire"
)

// joinScript serves a shell script that installs and starts an agent with
// a join token, so adding a server is one pasted line:
//
//	curl -fsSL "http://hub:8585/join/thj1_...?hub=192.168.1.10:7443" | sh
//
// It's public (the server being added has no session), but only answers for
// a valid, unused, unexpired token, which only an admin can create. A bad
// token gets a script that just explains the problem, since `curl -f` would
// otherwise print a bare HTTP error.
func (s *Server) joinScript(w http.ResponseWriter, r *http.Request) {
	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	fail := func(msg string) {
		_, _ = w.Write([]byte("#!/bin/sh\necho 'TainerHub: " + strings.ReplaceAll(msg, "'", "") + "' >&2\nexit 1\n"))
	}
	raw := r.PathValue("token")
	tok, err := wire.ParseJoinToken(raw)
	if err != nil {
		fail("this join link is malformed; copy the command again from Hosts -> Add host.")
		return
	}
	rec, err := s.Store.GetJoinToken(r.Context(), tok.ID)
	if err != nil || rec.Used || time.Now().After(rec.ExpiresAt) || subtle.ConstantTimeCompare(gateway.HashSecret(tok.Secret), rec.SecretHash) != 1 {
		fail("this join link was already used or has expired; in TainerHub use Hosts -> (the host's menu) -> New join token.")
		return
	}
	hub, err := s.agentAddrFor(r, r.URL.Query().Get("hub"))
	if err != nil {
		fail(err.Error())
		return
	}
	name := "this server"
	if h, err := s.Store.GetHost(r.Context(), rec.HostID); err == nil {
		name = h.Name
	}
	hubHost, _, _ := net.SplitHostPort(hub)
	_, _ = w.Write([]byte(renderJoinScript(name, hub, hubHost, agentCompose(hub, raw))))
}

func renderJoinScript(name, hub, hubHost, compose string) string {
	clean := func(s string) string { // only for the comments and messages below
		return strings.Map(func(r rune) rune {
			if r == '\'' || r == '"' || r == '`' || r == '$' || r == '\\' || r < 32 {
				return -1
			}
			return r
		}, s)
	}
	return strings.NewReplacer(
		"@NAME@", clean(name),
		"@HUB@", clean(hub),
		"@HUBHOST@", clean(hubHost),
		"@COMPOSE@", compose,
	).Replace(joinScriptTemplate)
}

const joinScriptTemplate = `#!/bin/sh
# TainerHub agent installer for @NAME@, generated by your hub.
# The join token inside works once and expires an hour after it was made.
set -eu
say() { printf '%s\n' "$*"; }
fail() { printf 'Error: %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || fail "Docker isn't installed. Install it first: https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || fail "The Docker Compose plugin is missing. Install docker-compose-plugin."
docker info >/dev/null 2>&1 || fail "Can't talk to Docker. Run this as root (e.g. ... | sudo sh) or as a user in the docker group."
if docker ps -a --format '{{.Names}}' | grep -qx tainerhub-agent; then
	fail "A TainerHub agent is already on this server (container tainerhub-agent). To replace it, run: docker rm -f tainerhub-agent  and then this command again."
fi

DIR="${TAINERHUB_AGENT_DIR:-$HOME/tainerhub-agent}"
mkdir -p "$DIR"
cd "$DIR"
if [ -f compose.yml ]; then mv compose.yml "compose.yml.bak.$(date +%s)"; fi
cat > compose.yml <<'TAINERHUB_COMPOSE_EOF'
@COMPOSE@TAINERHUB_COMPOSE_EOF

say "Starting the TainerHub agent (in $DIR) ..."
docker compose pull --quiet
docker compose up -d

i=0
until docker logs tainerhub-agent 2>&1 | grep -q "connected to hub"; do
	i=$((i + 1))
	if [ "$i" -gt 45 ]; then
		docker logs --tail 15 tainerhub-agent 2>&1 || true
		fail "The agent didn't reach the hub at @HUB@ within 90 seconds. Check that this server can reach @HUBHOST@ on port 7443."
	fi
	sleep 2
done
say ""
say "Connected. @NAME@ now shows up in TainerHub under Hosts."
`
